export function satelliteInfo(sat) {
  const modelKey = resolveSatelliteModelKey({ id: sat.id, variant: sat.variant })
  return {
    name: sat.name,
    description: sat.mission,
    stats: [
      { label: 'Altitude', value: `${sat.altitudeKm.toLocaleString()} km` },
      { label: 'Period', value: `${Math.round(sat.periodMin)} min` },
      { label: 'Orbit', value: sat.orbitType },
      { label: '3D model', value: modelAttribution(modelKey) },
    ],
  }
}
