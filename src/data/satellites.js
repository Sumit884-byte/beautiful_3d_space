function withProportionalOrbit(sat) {
  const orbitRadius = altitudeToOrbitRadius(sat.altitudeKm)
  const issOrbit = altitudeToOrbitRadius(408)
  const speed = 2.2 * Math.sqrt(issOrbit / orbitRadius)
  return { ...sat, orbitRadius, speed }
}

